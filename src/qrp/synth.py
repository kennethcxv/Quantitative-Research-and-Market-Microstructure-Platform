"""Deterministic synthetic L2 feed: a zero-intelligence limit order book.

Everything this produces is SYNTHETIC. It exists so tests and the bundled demo can run without
licensed data, and so the pipeline sees the awkward parts of a real feed: multi-level sweeps,
packet loss followed by a recovery snapshot, receive latency and activity regimes.

Model (in the spirit of Smith, Farmer et al. 2003 and Cont, Stoikov & Talreja 2010):
messages arrive as a Poisson process whose rate switches between a calm and an active regime.
Each message is a limit order placed k ticks behind the opposite best quote (k geometric, so it
can improve the spread), a cancellation at one of the top levels, or a market order that sweeps
the opposite side. Order-book imbalance predicts the next mid move in this model for a mechanical
reason: market orders deplete the thin side first. That gives the research pipeline a real,
known signal to find, alongside costs that are large relative to it.
"""

from __future__ import annotations

import bisect
import datetime as dt
from typing import Any

import numpy as np
import polars as pl
from pydantic import BaseModel

from qrp.schemas import BOOK, SNAPSHOT, TRADE, Capabilities, SourceInfo, StreamInfo, conform

STREAM = "feed"


class SynthConfig(BaseModel):
    symbol: str = "SYNTH"
    seed: int = 7
    start_date: dt.date = dt.date(2024, 1, 2)
    n_days: int = 3
    session_start_utc: dt.time = dt.time(14, 30)
    session_seconds: int = 4 * 3600
    tick_size: float = 0.01
    start_price: float = 100.0
    rate_calm: float = 6.0  # messages per second
    rate_active: float = 18.0
    regime_mean_seconds: float = 900.0
    p_market: float = 0.10
    p_limit: float = 0.50  # remainder are cancellations
    placement_p: float = 0.35  # geometric parameter for the distance from the opposite best
    mean_order_size: float = 4.0
    initial_levels: int = 10
    cancel_depth: int = 8  # cancellations hit one of the top N levels
    latency_median_us: float = 400.0
    gaps_per_day: int = 1  # lost-packet episodes, each followed by a recovery snapshot
    gap_messages: int = 40
    recovery_seconds: float = 2.0


def synthetic_source() -> SourceInfo:
    return SourceInfo(
        name="qrp synthetic zero-intelligence order book",
        license="CC0-1.0 (generated data, no third-party content)",
        synthetic=True,
        notes="Generated by qrp.synth. Results on this data say nothing about real markets.",
    )


def synthetic_capabilities() -> Capabilities:
    return Capabilities(
        book_depth=None,
        has_trades=True,
        recv_time="measured",
        event_time="exchange",
        streams={STREAM: StreamInfo(sequencing="contiguous", description="unified feed seq")},
    )


class _Book:
    """Integer-tick book used only by the generator."""

    def __init__(self) -> None:
        self.size: dict[int, dict[int, int]] = {1: {}, -1: {}}
        self.ticks: dict[int, list[int]] = {1: [], -1: []}  # ascending

    def best(self, side: int) -> int | None:
        t = self.ticks[side]
        if not t:
            return None
        return t[-1] if side == 1 else t[0]

    def set(self, side: int, tick: int, qty: int) -> None:
        levels, ticks = self.size[side], self.ticks[side]
        if qty > 0:
            if tick not in levels:
                bisect.insort(ticks, tick)
            levels[tick] = qty
        elif tick in levels:
            del levels[tick]
            ticks.pop(bisect.bisect_left(ticks, tick))

    def top(self, side: int, n: int) -> list[int]:
        t = self.ticks[side]
        return t[::-1][:n] if side == 1 else t[:n]


def generate(cfg: SynthConfig | None = None) -> pl.DataFrame:
    """Return the synthetic feed as a conformed ``qrp.events.v1`` frame in capture order."""
    cfg = cfg or SynthConfig()
    rng = np.random.default_rng(cfg.seed)
    per_unit = round(1 / cfg.tick_size)
    cols: dict[str, list[Any]] = {
        k: [] for k in ("seq", "event", "recv", "kind", "side", "tick", "size")
    }
    seq = 0
    recv_prev = 0
    mid_tick = round(cfg.start_price * per_unit)
    latency_sigma = 0.6

    def emit(t_event: int, rows: list[tuple[str, int, int, int]], visible: bool) -> None:
        nonlocal seq, recv_prev
        seq += 1
        if not visible:  # lost in transit: the exchange processed it, we never see it
            return
        latency = int(cfg.latency_median_us * 1000 * np.exp(latency_sigma * rng.standard_normal()))
        recv = max(recv_prev, t_event + latency)
        recv_prev = recv
        for kind, side, tick, size in rows:
            cols["seq"].append(seq)
            cols["event"].append(t_event)
            cols["recv"].append(recv)
            cols["kind"].append(kind)
            cols["side"].append(side)
            cols["tick"].append(tick)
            cols["size"].append(size)

    def snapshot_rows(book: _Book) -> list[tuple[str, int, int, int]]:
        return [
            (SNAPSHOT, side, tick, book.size[side][tick])
            for side in (1, -1)
            for tick in book.ticks[side]
        ]

    def order_size() -> int:
        return int(rng.geometric(1 / cfg.mean_order_size))

    for day in range(cfg.n_days):
        date = cfg.start_date + dt.timedelta(days=day)
        start = dt.datetime.combine(date, cfg.session_start_utc, tzinfo=dt.UTC)
        t0 = int(start.timestamp()) * 10**9
        t_end = t0 + cfg.session_seconds * 10**9
        book = _Book()
        for i in range(1, cfg.initial_levels + 1):
            book.set(1, mid_tick - i, order_size() * 3)
            book.set(-1, mid_tick + i, order_size() * 3)
        emit(t0, snapshot_rows(book), visible=True)

        gap_starts = sorted(rng.uniform(0.1, 0.9, cfg.gaps_per_day) * cfg.session_seconds * 1e9)
        gap_starts_ns = [t0 + int(g) for g in gap_starts]
        lost_left, recover_at = 0, None
        active = False
        next_switch = t0 + int(rng.exponential(cfg.regime_mean_seconds) * 1e9)
        t = t0
        while True:
            rate = cfg.rate_active if active else cfg.rate_calm
            t += int(rng.exponential(1.0 / rate) * 1e9) + 1
            if t >= t_end:
                break
            if t >= next_switch:
                active = not active
                next_switch = t + int(rng.exponential(cfg.regime_mean_seconds) * 1e9)
            if gap_starts_ns and t >= gap_starts_ns[0]:
                gap_starts_ns.pop(0)
                lost_left = cfg.gap_messages
            if recover_at is not None and t >= recover_at:
                emit(t, snapshot_rows(book), visible=True)
                recover_at = None
                continue

            rows: list[tuple[str, int, int, int]] = []
            u = rng.random()
            side = 1 if rng.random() < 0.5 else -1
            if u < cfg.p_market:
                # Market order from `side` sweeps the opposite side of the book.
                remaining = order_size() * 2
                book_side = -side
                while remaining > 0:
                    best = book.best(book_side)
                    if best is None or len(book.ticks[book_side]) <= 2:
                        break  # keep a minimum book; the rest of the order is not filled
                    take = min(remaining, book.size[book_side][best])
                    remaining -= take
                    left = book.size[book_side][best] - take
                    book.set(book_side, best, left)
                    rows.append((TRADE, side, best, take))
                    rows.append((BOOK, book_side, best, left))
            elif u < cfg.p_market + cfg.p_limit or len(book.ticks[side]) < 3:
                opposite = book.best(-side)
                assert opposite is not None
                distance = int(rng.geometric(cfg.placement_p))
                tick = opposite - side * distance
                qty = book.size[side].get(tick, 0) + order_size()
                book.set(side, tick, qty)
                rows.append((BOOK, side, tick, qty))
            else:
                levels = book.top(side, cfg.cancel_depth)
                tick = levels[int(rng.integers(len(levels)))]
                qty = max(0, book.size[side][tick] - order_size())
                book.set(side, tick, qty)
                rows.append((BOOK, side, tick, qty))
            if not rows:
                continue
            if lost_left > 0:
                lost_left -= 1
                emit(t, rows, visible=False)
                if lost_left == 0:
                    recover_at = t + int(cfg.recovery_seconds * 1e9)
            else:
                emit(t, rows, visible=True)
        bid, ask = book.best(1), book.best(-1)
        if bid is not None and ask is not None:
            mid_tick = (bid + ask) // 2

    n = len(cols["seq"])
    return conform(
        pl.DataFrame(
            {
                "symbol": [cfg.symbol] * n,
                "stream": [STREAM] * n,
                "seq": cols["seq"],
                "event_time_ns": cols["event"],
                "recv_time_ns": cols["recv"],
                "kind": cols["kind"],
                "side": cols["side"],
                "price": np.asarray(cols["tick"], dtype=np.float64) / per_unit,
                "size": np.asarray(cols["size"], dtype=np.float64),
            }
        )
    )
